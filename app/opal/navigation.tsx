"use client";
import { useState, useEffect } from "react";
import { usePathname } from "next/navigation";
import {
	IconComments,
	IconBooks,
	IconBell,
	IconFolderBookmark,
	IconStore,
	IconAgent,
	IconPuzzlePiece,
	IconGear,
	IconUserGroup,
	IconImagePortrait,
} from "@optiaxiom/icons";

export function useOpalNav() {
	const pathname = usePathname();
	const [imLayout, setImLayout] = useState<string>("A");

	useEffect(() => {
		try {
			const stored = localStorage.getItem("im-layout");
			if (stored) setImLayout(JSON.parse(stored));
		} catch {
			/* ignore */
		}
		const handler = (e: Event) => setImLayout((e as CustomEvent<string>).detail);
		window.addEventListener("im-layout-change", handler);
		return () => window.removeEventListener("im-layout-change", handler);
	}, []);

	const isCompactIm = imLayout === "B" || imLayout === "C";

	function active(highlight: string, exact = false) {
		if (exact) return pathname === highlight;
		return pathname.startsWith(highlight);
	}

	return [
		{
			label: isCompactIm ? "Chats" : "Opal Chats",
			url: "/opal",
			highlight: "/opal",
			icon: isCompactIm ? (
				<IconComments filled={active("/opal", true)} />
			) : (
				<span
					style={{
						display: "inline-flex",
						width: 24,
						height: 24,
						minWidth: 24,
						minHeight: 24,
						maxWidth: 24,
						maxHeight: 24,
						borderRadius: "50%",
						overflow: "hidden",
						flexShrink: 0,
					}}
				>
					<img
						src="/opal-icon-nav.png"
						alt=""
						style={{
							width: "100%",
							height: "100%",
							objectFit: "cover",
							display: "block",
						}}
					/>
				</span>
			),
			exact: true,
			customLayout: true,
		},
		{
			label: imLayout === "B" ? "Messages" : imLayout === "C" ? "Spaces" : "Threads",
			url: `/opal/im?layout=${imLayout}`,
			highlight: "/opal/im",
			icon: isCompactIm
				? <IconUserGroup filled={active("/opal/im")} />
				: <IconComments filled={active("/opal/im")} />,
			customLayout: true,
		},
		{
			label: "Artifacts",
			url: "/opal/artifacts",
			highlight: "/opal/artifacts",
			icon: <IconBooks filled={active("/opal/artifacts")} />,
			description: "Browse and manage all files and outputs generated by your Opal agents.",
			hidePageHeader: true,
		},
		{
			label: "Activities",
			url: "/opal/notifications",
			highlight: "/opal/notifications",
			icon: <IconBell filled={active("/opal/notifications")} />,
			customLayout: true,
		},
		{ label: "Configurations" },
		{
			label: "Context",
			url: "/opal/context",
			highlight: "/opal/context",
			customLayout: true,
			icon: <IconFolderBookmark filled={active("/opal/context")} />,
		},
		{
			label: "Virtual Teammates",
			url: "/opal/virtual-teammates",
			highlight: "/opal/virtual-teammates",
			icon: <IconImagePortrait filled={active("/opal/virtual-teammates")} />,
			customLayout: true,
		},
		{
			label: "Directory",
			url: "/opal/marketplace",
			highlight: "/opal/marketplace",
			icon: <IconStore filled={active("/opal/marketplace")} />,
		},
		{
			label: "Agents",
			url: "/opal/agents",
			highlight: "/opal/agents",
			icon: <IconAgent filled={active("/opal/agents")} />,
			customLayout: true,
		},
		{
			label: "Connectors",
			url: "/opal/connectors",
			highlight: "/opal/connectors",
			icon: <IconPuzzlePiece filled={active("/opal/connectors")} />,
			hidePageHeader: true,
		},
		{
			label: "Settings",
			url: "/opal/settings",
			highlight: "/opal/settings",
			icon: <IconGear filled={active("/opal/settings")} />,
		},
	];
}
