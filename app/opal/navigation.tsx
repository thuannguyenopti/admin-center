"use client";
import {useState, useEffect} from "react";
import {
	IconComments,
	IconBooks,
	IconBell,
	IconFolderBookmark,
	IconSquareUser,
	IconAgent,
	IconPuzzlePiece,
	IconGear,
	IconUserGroup,
} from "@optiaxiom/icons";

export function useOpalNav() {
	const [imLayout, setImLayout] = useState<string>("A");
	useEffect(() => {
		try {
			const stored = localStorage.getItem("im-layout");
			if (stored) setImLayout(JSON.parse(stored));
		} catch {
			/* ignore */
		}
		const handler = (e: Event) => setImLayout((e as CustomEvent<string>).detail);
		window.addEventListener("im-layout-change", handler);
		return () => window.removeEventListener("im-layout-change", handler);
	}, []);

	const isCompactIm = imLayout === "B" || imLayout === "C";

	return [
		{
			label: isCompactIm ? "Chats" : "Opal Chats",
			url: "/opal",
			highlight: "/opal",
			icon: isCompactIm ? (
				<IconComments />
			) : (
				<span
					style={{
						display: "inline-flex",
						width: 24,
						height: 24,
						minWidth: 24,
						minHeight: 24,
						maxWidth: 24,
						maxHeight: 24,
						borderRadius: "50%",
						overflow: "hidden",
						flexShrink: 0,
					}}
				>
					<img
						src="/opal-icon-nav.png"
						alt=""
						style={{
							width: "100%",
							height: "100%",
							objectFit: "cover",
							display: "block",
						}}
					/>
				</span>
			),
			exact: true,
			customLayout: true,
		},
		{
			label: imLayout === "B" ? "Messages" : imLayout === "C" ? "Spaces" : "Threads",
			url: `/opal/im?layout=${imLayout}`,
			highlight: "/opal/im",
			icon: isCompactIm ? <IconUserGroup /> : <IconComments />,
			customLayout: true,
		},
		{
			label: "Artifacts",
			url: "/opal/artifacts",
			highlight: "/opal/artifacts",
			icon: <IconBooks />,
			description: "Browse and manage all files and outputs generated by your Opal agents.",
			hidePageHeader: true,
		},
		{
			label: "Activities",
			url: "/opal/notifications",
			highlight: "/opal/notifications",
			icon: <IconBell />,
			customLayout: true,
		},
		{label: "Configurations"},
		{
			label: "Context",
			url: "/opal/context",
			highlight: "/opal/context",
			customLayout: false,
			description:
				"Tailor Opal's output for yourself or your organization by providing specific context and guidance in the form of files, skills, memory, and RAG.",
			icon: <IconFolderBookmark />,
			children: [
				{
					label: "Stride DS Setup",
					url: "/opal/context/stride-ds-setup",
					customLayout: true,
				},
			],
		},
		{
			label: "Virtual Teammates",
			url: "/opal/virtual-teammates",
			highlight: "/opal/virtual-teammates",
			icon: <IconSquareUser />,
			customLayout: true,
		},
		{
			label: "Agents",
			url: "/opal/agents",
			highlight: "/opal/agents",
			icon: <IconAgent />,
			customLayout: true,
		},
		{
			label: "Connectors",
			url: "/opal/connectors",
			highlight: "/opal/connectors",
			icon: <IconPuzzlePiece />,
			hidePageHeader: true,
		},
		{
			label: "Settings",
			url: "/opal/settings",
			highlight: "/opal/settings",
			icon: <IconGear />,
		},
	];
}
