// ── Option B: blinking bulb + rotating tips ───────────────────────────────────

function Hint1({ onAddToPrompt, onNavigate, duration, onAdvance }: VariantProps) {
  const [index, setIndex] = useState(0);
  const [visible, setVisible] = useState(true);
  const [bulbKey, setBulbKey] = useState(0);
  const timerRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  const advance = useCallback(() => {
    setVisible(false);
    setTimeout(() => {
      setIndex((i) => (i + 1) % HINTS.length);
      setBulbKey((k) => k + 1);
      setVisible(true);
      onAdvance?.();
    }, 350);
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [onAdvance]);

  useEffect(() => {
    timerRef.current = setTimeout(advance, duration);
    return () => { if (timerRef.current) clearTimeout(timerRef.current); };
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [index, duration]);

  return (
    <HintRow bulbKey={bulbKey} bulbStyle={{ animation: "opal-hint-bulb-pulse 2s ease-in-out infinite" }}>
      <span
        onClick={() => handleHintClick(HINTS[index], onAddToPrompt, onNavigate)}
        style={{
          display: "inline-flex",
          alignItems: "center",
          gap: "8px",
          opacity: visible ? 1 : 0,
          transition: "opacity 0.35s ease",
          fontSize: "14px",
          color: "var(--ax-colors-fg-default)",
          cursor: getHintAction(HINTS[index]).type !== "none" ? "pointer" : "default",
        }}
      >
        {HINTS[index]}
        <AddToPromptButton text={HINTS[index]} onAddToPrompt={onAddToPrompt} onNavigate={onNavigate} />
      </span>
    </HintRow>
  );
}

