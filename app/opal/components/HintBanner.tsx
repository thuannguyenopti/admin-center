const OPTION_LABELS: Record<HintVariant, string> = {
  "A": "Typewriter",
  "B": "Blinking bulb, synced fade",
  "C": "Blinking cursor",
  "D": "Wiggling bulb",
};

const DURATION_OPTIONS = [10, 15, 20, 30]; // seconds

export function HintBannerWithToggle({ onAddToPrompt, showConfig = true }: { onAddToPrompt: (t: string) => void; showConfig?: boolean }) {
  const router = useRouter();
  const handleNavigate = useCallback((href: string) => router.push(href), [router]);
  const [variant, setVariant] = useState<HintVariant>("A");
  const [hoveredVariant, setHoveredVariant] = useState<HintVariant | null>(null);
  const [durationIndex, setDurationIndex] = useState(1); // index into DURATION_OPTIONS; default = 15s
  const duration = DURATION_OPTIONS[durationIndex];
  const [elapsed, setElapsed] = useState(0);    // seconds since last advance

  const activeLabel = OPTION_LABELS[hoveredVariant ?? variant];
  const remaining = Math.max(0, duration - elapsed);

  // Countdown ticker
  useEffect(() => {
    const id = setInterval(() => setElapsed((e) => e + 1), 1_000);
    return () => clearInterval(id);
  }, []);

  // Reset countdown on variant or duration change
  useEffect(() => {
    setElapsed(0);
  }, [variant, durationIndex]);

  const handleAdvance = useCallback(() => setElapsed(0), []);

  return (
    <Box style={{ maxWidth: "768px", width: "100%", margin: "0 auto" }}>
      <HintBanner variant={variant} onAddToPrompt={onAddToPrompt} onNavigate={handleNavigate} duration={duration * 1_000} onAdvance={handleAdvance} />
      {showConfig && <div
        style={{
          position: "fixed",
          top: "56px",
          right: "12px",
          paddingTop: "6px",
          display: "flex",
          flexDirection: "column",
          alignItems: "flex-end",
          gap: "4px",
          zIndex: 9999,
        }}
      >
        {/* Single row: slider | variant buttons | countdown */}
        <div style={{ display: "flex", alignItems: "center", gap: "8px" }}>
          {/* Duration slider — 3 steps: 10 / 20 / 30 */}
          <Box display="flex" alignItems="center" gap="6">
            <Box style={{ width: "80px" }}>
              <Range
                min={0}
                max={3}
                step={1}
                value={durationIndex}
                onValueChange={setDurationIndex}
              />
            </Box>
            <span style={{
              fontSize: "11px",
              color: "var(--ax-colors-fg-tertiary)",
              fontVariantNumeric: "tabular-nums",
              minWidth: "24px",
            }}>
              {duration}s
            </span>
          </Box>

          {/* Divider */}
          <div style={{ width: 1, height: 16, background: "var(--ax-colors-border-secondary)", flexShrink: 0 }} />

          {/* Variant buttons */}
          <div style={{ display: "flex", gap: "4px" }}>
            {(["A", "B", "C", "D"] as HintVariant[]).map((v) => (
              <Button
                key={v}
                appearance={variant === v ? "primary" : "subtle"}
                size="sm"
                onClick={() => setVariant(v)}
                onMouseEnter={() => setHoveredVariant(v)}
                onMouseLeave={() => setHoveredVariant(null)}
              >
                {v}
              </Button>
            ))}
          </div>

          {/* Countdown */}
          <span style={{
            fontSize: "11px",
            color: remaining <= 3 ? "var(--ax-colors-fg-warning)" : "var(--ax-colors-fg-tertiary)",
            minWidth: "22px",
            textAlign: "right",
            fontVariantNumeric: "tabular-nums",
          }}>
            {remaining}s
          </span>
        </div>

        {/* Variant label */}
        <span style={{ fontSize: "10px", color: "var(--ax-colors-fg-tertiary)", whiteSpace: "nowrap" }}>
          {activeLabel}
        </span>
      </div>}
    </Box>
  );
}
