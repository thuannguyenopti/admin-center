// ── Shared helpers ────────────────────────────────────────────────────────────

function addToPromptAndFocus(hint: string, onAddToPrompt: (t: string) => void) {
  const action = getHintAction(hint);
  if (action.type === "none" || action.type === "navigate" || action.type === "click") return;
  onAddToPrompt(getInsertText(hint));
  (document.querySelector("textarea") as HTMLTextAreaElement | null)?.focus();
}

function handleHintClick(hint: string, onAddToPrompt: (t: string) => void, onNavigate: (href: string) => void) {
  const action = getHintAction(hint);
  if (action.type === "navigate") { onNavigate(action.href); return; }
  if (action.type === "click") { (document.querySelector(action.selector) as HTMLElement | null)?.click(); return; }
  if (action.type !== "none") addToPromptAndFocus(hint, onAddToPrompt);
}

function AddToPromptButton({
  text,
  onAddToPrompt,
  onNavigate,
}: {
  text: string;
  onAddToPrompt: (t: string) => void;
  onNavigate: (href: string) => void;
}) {
  const action = getHintAction(text);
  if (action.type === "none") return null;

  if (action.type === "navigate") {
    return (
      <Button
        appearance="subtle"
        size="sm"
        onClick={(e: React.MouseEvent) => { e.stopPropagation(); onNavigate(action.href); }}
        style={{ flexShrink: 0 }}
      >
        Take me there →
      </Button>
    );
  }

  if (action.type === "click") {
    return (
      <Button
        appearance="subtle"
        size="sm"
        onClick={(e: React.MouseEvent) => {
          e.stopPropagation();
          (document.querySelector(action.selector) as HTMLElement | null)?.click();
        }}
        style={{ flexShrink: 0 }}
      >
        Try it out ↓
      </Button>
    );
  }

  const label = "Try it out ↓";
  return (
    <Button
      appearance="subtle"
      size="sm"
      onClick={(e: React.MouseEvent) => { e.stopPropagation(); addToPromptAndFocus(text, onAddToPrompt); }}
      style={{ flexShrink: 0 }}
    >
      {label}
    </Button>
  );
}

