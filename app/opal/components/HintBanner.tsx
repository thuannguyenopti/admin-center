function getHintAction(hint: string): HintAction {
  return HINT_ACTIONS[hint] ?? { type: "tryout", prompt: hint };
}

function getInsertText(hint: string): string {
  const action = getHintAction(hint);
  if (action.type === "smart") return action.insert;
  if (action.type === "tryout") return action.prompt;
  return hint;
}

