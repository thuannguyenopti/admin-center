// ── Option A: typewriter + bulb pop ──────────────────────────────────────────

const TYPE_SPEED = 18;
const ERASE_SPEED = 12;

function Hint4({ onAddToPrompt, onNavigate, duration, onAdvance }: VariantProps) {
  const [tipIndex, setTipIndex] = useState(0);
  const [displayed, setDisplayed] = useState("");
  const [phase, setPhase] = useState<"typing" | "holding" | "erasing">("typing");
  const [bulbKey, setBulbKey] = useState(0);
  const frame = useRef<ReturnType<typeof setTimeout> | null>(null);

  useEffect(() => {
    const tip = HINTS[tipIndex];
    if (phase === "typing") {
      if (displayed.length < tip.length) {
        frame.current = setTimeout(() => setDisplayed(tip.slice(0, displayed.length + 1)), TYPE_SPEED);
      } else {
        setPhase("holding");
      }
    } else if (phase === "holding") {
      frame.current = setTimeout(() => setPhase("erasing"), duration);
    } else if (phase === "erasing") {
      if (displayed.length > 0) {
        frame.current = setTimeout(() => setDisplayed((d) => d.slice(0, -1)), ERASE_SPEED);
      } else {
        const next = (tipIndex + 1) % HINTS.length;
        setTipIndex(next);
        setBulbKey((k) => k + 1);
        setPhase("typing");
        onAdvance?.();
      }
    }
    return () => { if (frame.current) clearTimeout(frame.current); };
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [phase, displayed, tipIndex, duration]);

  const showCursor = phase === "typing";

  return (
    <HintRow
      bulbKey={bulbKey}
      bulbStyle={{ animation: "opal-hint-bulb-pop 0.45s cubic-bezier(0.36,0.07,0.19,0.97)" }}
    >
      <span
        onClick={() => handleHintClick(HINTS[tipIndex], onAddToPrompt, onNavigate)}
        style={{
          display: "inline-flex",
          alignItems: "center",
          gap: "8px",
          fontSize: "14px",
          color: "var(--ax-colors-fg-default)",
          minHeight: "20px",
          cursor: getHintAction(HINTS[tipIndex]).type !== "none" ? "pointer" : "default",
        }}
      >
        <span style={{ display: "inline-flex", alignItems: "center" }}>
        {displayed}
        {showCursor && (
          <span
            style={{
              display: "inline-block",
              width: "1.5px",
              height: "13px",
              backgroundColor: "var(--ax-colors-fg-default)",
              marginLeft: "2px",
              verticalAlign: "middle",
              opacity: 1,
            }}
          />
        )}
        </span>
        <span style={{
          opacity: phase === "holding" ? 1 : 0,
          transition: phase === "holding" ? "opacity 0.3s ease 0.25s" : "opacity 0.15s ease",
          pointerEvents: phase === "holding" ? "auto" : "none",
        }}>
          <AddToPromptButton text={HINTS[tipIndex]} onAddToPrompt={onAddToPrompt} onNavigate={onNavigate} />
        </span>
      </span>
    </HintRow>
  );
}

// ── Public component ──────────────────────────────────────────────────────────

type HintProps = { onAddToPrompt: (t: string) => void; onNavigate: (href: string) => void };

export function HintBanner({
  variant,
  onAddToPrompt,
  onNavigate,
  duration,
  onAdvance,
}: { variant: HintVariant; duration: number; onAdvance?: () => void } & HintProps) {
  if (variant === "A") return <Hint4 onAddToPrompt={onAddToPrompt} onNavigate={onNavigate} duration={duration} onAdvance={onAdvance} />;
  if (variant === "B") return <Hint1 onAddToPrompt={onAddToPrompt} onNavigate={onNavigate} duration={duration} onAdvance={onAdvance} />;
  if (variant === "C") return <Hint2 onAddToPrompt={onAddToPrompt} onNavigate={onNavigate} duration={duration} onAdvance={onAdvance} />;
  return <Hint3 onAddToPrompt={onAddToPrompt} onNavigate={onNavigate} duration={duration} onAdvance={onAdvance} />;
}

