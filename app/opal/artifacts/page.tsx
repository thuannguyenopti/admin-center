export default function ArtifactsPage() {
    const [typeFilter, setTypeFilter] = useState("All");
    const [search, setSearch] = useState("");

    const filtered = artifacts.filter((a) => {
        const matchesType = typeFilter === "All" || a.type === typeFilter;
        const matchesSearch =
            search === "" ||
            a.name.toLowerCase().includes(search.toLowerCase()) ||
            a.agent.name.toLowerCase().includes(search.toLowerCase());
        return matchesType && matchesSearch;
    });

    return (
        <Box display="flex" flexDirection="column" gap="24" overflow="auto" h="full">
            {/* Header */}
            <Box display="flex" flexDirection="column" gap="8">
                <Heading level="1" fontSize="2xl">Artifacts</Heading>
                <Text color="fg.secondary">
                    Browse and manage all files and outputs generated by your Opal agents.
                </Text>
            </Box>

            {/* Toolbar */}
            <Box display="flex" justifyContent="space-between" alignItems="center">
                <Box display="flex" gap="12" alignItems="center">
                    <Box className="w-[300px]">
                        <Input
                            placeholder="Search artifacts..."
                            value={search}
                            onChange={(e) => setSearch(e.target.value)}
                        />
                    </Box>

                    <DropdownMenu>
                        <DropdownMenuTrigger asChild>
                            <LabelMenuButton label="Type" h="40">
                                {typeFilter}
                            </LabelMenuButton>
                        </DropdownMenuTrigger>
                        <DropdownMenuContent>
                            {["All", "Document", "Image", "Code"].map((t) => (
                                <DropdownMenuItem key={t} onClick={() => setTypeFilter(t)}>
                                    <Box display="flex" alignItems="center" gap="8">
                                        {t !== "All" && typeIcon[t]}
                                        {t}
                                    </Box>
                                </DropdownMenuItem>
                            ))}
                        </DropdownMenuContent>
                    </DropdownMenu>
                </Box>

                <Button appearance="default" icon={<IconDownload size={16} />}>
                    Download all
                </Button>
            </Box>

            {/* Table */}
            <Table>
                <thead>
                    <Tr>
                        <Th>Type</Th>
                        <Th>Name</Th>
                        <Th>Source Agent</Th>
                        <Th>Created by</Th>
                        <Th>Created</Th>
                        <Th>Size</Th>
                        <Th>Status</Th>
                        <Th></Th>
                    </Tr>
                </thead>
                <tbody>
                    {filtered.map((artifact) => (
                        <Tr key={artifact.id}>
                            <Td>
                                <Box color="fg.secondary">{typeIcon[artifact.type]}</Box>
                            </Td>
                            <Td>
                                <Text fontWeight="500">{artifact.name}</Text>
                            </Td>
                            <Td>
                                <Box display="flex" alignItems="center" gap="8" color="fg.secondary">
                                    {artifact.agent.type === "workflow" ? (
                                        <IconCodeBranch size={14} />
                                    ) : (
                                        <IconAgent size={14} />
                                    )}
                                    <Text fontSize="sm">{artifact.agent.name}</Text>
                                </Box>
                            </Td>
                            <Td>
                                <Box display="flex" alignItems="center" gap="8">
                                    <Avatar
                                        name={artifact.createdBy.name}
                                        src={artifact.createdBy.avatar}
                                        size="sm"
                                    />
                                    <Text fontSize="sm">{artifact.createdBy.name}</Text>
                                </Box>
                            </Td>
                            <Td>
                                <Text fontSize="sm">{artifact.created}</Text>
                            </Td>
                            <Td>
                                <Text fontSize="sm" color="fg.secondary">{artifact.size}</Text>
                            </Td>
                            <Td>
                                <Badge intent={artifact.status === "Ready" ? "success" : "information"}>
                                    {artifact.status}
                                </Badge>
                            </Td>
                            <Td type="button">
                                <DropdownMenu>
                                    <DropdownMenuTrigger asChild>
                                        <Button
                                            appearance="subtle"
                                            size="sm"
                                            icon={<IconEllipsisSolid size={16} />}
                                            aria-label="Options"
                                        />
                                    </DropdownMenuTrigger>
                                    <DropdownMenuContent align="end">
                                        <DropdownMenuItem>
                                            <Box display="flex" alignItems="center" gap="8">
                                                <IconDownload size={14} />
                                                Download
                                            </Box>
                                        </DropdownMenuItem>
                                        <DropdownMenuItem style={{ color: "var(--ax-colors-fg-danger)" }}>
                                            <IconTrashCan size={14} />
                                            Delete
                                        </DropdownMenuItem>
                                    </DropdownMenuContent>
                                </DropdownMenu>
                            </Td>
                        </Tr>
                    ))}
                </tbody>
            </Table>
        </Box>
    );
}
