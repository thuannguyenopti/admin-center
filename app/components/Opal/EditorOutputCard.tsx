"use client";

import { Box, Badge } from "@optiaxiom/react";
import { Text } from "../Text";
import { Button } from "../Button";
import {
  IconFileLines,
  IconPenToSquare,
  IconDownload,
  IconCircleCheck,
} from "@optimizely/axiom-icons";

export type EditorFileType = "markdown" | "html" | "code" | "docx" | "xlsx";

type EditorOutputCardProps = {
  filename: string;
  fileType?: EditorFileType;
  wordCount?: number;
  preview?: string;
  agentName?: string;
  onEdit: () => void;
  onDownload?: () => void;
};

const FILE_TYPE_LABELS: Record<EditorFileType, string> = {
  markdown: "Markdown",
  html: "HTML",
  code: "Code",
  docx: "Word",
  xlsx: "Excel",
};

const FILE_TYPE_INTENT: Record<EditorFileType, "neutral" | "information" | "success" | "primary"> = {
  markdown: "information",
  html: "primary",
  code: "neutral",
  docx: "information",
  xlsx: "success",
};

export function EditorOutputCard({
  filename,
  fileType = "markdown",
  wordCount,
  preview,
  agentName,
  onEdit,
  onDownload,
}: EditorOutputCardProps) {
  return (
    <Box
      border="1"
      borderColor="border.secondary"
      rounded="xl"
      display="flex"
      flexDirection="column"
      style={{
        background: "var(--ax-colors-bg-default)",
        width: "100%",
        overflow: "hidden",
      }}
    >
      {/* ── Header ── */}
      <Box
        display="flex"
        alignItems="center"
        gap="8"
        px="16"
        py="12"
        borderB="1"
        borderColor="border.secondary"
      >
        <Box
          display="flex"
          alignItems="center"
          justifyContent="center"
          style={{ width: 32, height: 32, flexShrink: 0 }}
          bg="bg.accent.subtle"
          rounded="md"
        >
          <IconFileLines size={16} style={{ color: "var(--ax-colors-fg-accent)" }} />
        </Box>
        <Box flex="1" display="flex" flexDirection="column" gap="2">
          <Text fontSize="md" fontWeight="600" color="fg.default">
            {filename}
          </Text>
          {agentName && (
            <Text fontSize="xs" color="fg.tertiary">
              Generated by {agentName}
            </Text>
          )}
        </Box>
        <Box display="flex" alignItems="center" gap="6">
          <Badge intent={FILE_TYPE_INTENT[fileType]} variant="subtle">
            {FILE_TYPE_LABELS[fileType]}
          </Badge>
          <Box display="flex" alignItems="center" gap="4">
            <IconCircleCheck size={12} style={{ color: "var(--ax-colors-fg-success)" }} />
            <Text fontSize="xs" color="fg.success">Ready</Text>
          </Box>
        </Box>
      </Box>

      {/* ── Preview ── */}
      {preview && (
        <Box
          px="16"
          py="12"
          borderB="1"
          borderColor="border.secondary"
          style={{ position: "relative", maxHeight: 100, overflow: "hidden" }}
        >
          <Box
            style={{
              fontFamily: "var(--ax-fonts-mono, monospace)",
              fontSize: 12,
              lineHeight: 1.6,
              color: "var(--ax-colors-fg-secondary)",
              whiteSpace: "pre-wrap",
              wordBreak: "break-word",
            }}
          >
            {preview}
          </Box>
          {/* Fade out */}
          <Box
            style={{
              position: "absolute",
              bottom: 0,
              left: 0,
              right: 0,
              height: 36,
              background:
                "linear-gradient(to bottom, transparent, var(--ax-colors-bg-default))",
              pointerEvents: "none",
            }}
          />
        </Box>
      )}

      {/* ── Footer ── */}
      <Box
        display="flex"
        alignItems="center"
        justifyContent="space-between"
        px="16"
        py="10"
        gap="8"
      >
        <Box display="flex" alignItems="center" gap="8">
          {wordCount != null && (
            <Text fontSize="xs" color="fg.tertiary">
              {wordCount.toLocaleString()} words
            </Text>
          )}
        </Box>
        <Box display="flex" alignItems="center" gap="8">
          {onDownload && (
            <Button
              appearance="subtle"
              size="sm"
              icon={<IconDownload size={14} />}
              onClick={onDownload}
            >
              Download
            </Button>
          )}
          <Button
            appearance="primary"
            size="sm"
            icon={<IconPenToSquare size={14} />}
            onClick={onEdit}
          >
            Edit
          </Button>
        </Box>
      </Box>
    </Box>
  );
}
